"use client";

import { useState, useTransition } from "react";
import { Sparkles, Loader2 } from "lucide-react";
import { generateNarrative } from "@/app/insights/actions";
import { buttonClass } from "@/components/ui";

export function NarrativeButton({ period, periodKey }: { period: "week" | "month"; periodKey: string }) {
  const [res, setRes] = useState<{ ok: boolean; text?: string; error?: string } | null>(null);
  const [pending, start] = useTransition();
  return (
    <div>
      <button type="button" className={buttonClass("secondary", "sm")} disabled={pending} onClick={() => start(async () => setRes(await generateNarrative(period, periodKey)))}>
        {pending ? <Loader2 className="size-3.5 animate-spin" /> : <Sparkles className="size-3.5" />}
        {res?.ok ? "Regenerate summary" : "Write AI summary"}
      </button>
      {res && (
        <div className={res.ok ? "mt-3 rounded-xl bg-fill p-4 text-[13px] leading-6 whitespace-pre-wrap text-ink-2 shadow-[0_0_0_1px_var(--color-line)]" : "mt-3 rounded-xl bg-warn-soft p-3 text-[12.5px] text-warn-ink"}>
          {res.ok ? res.text : res.error}
          {res.ok && <div className="mt-2 text-[11px] text-ink-3">Generated by Claude from the statistics on this page only. Check it against the numbers.</div>}
        </div>
      )}
    </div>
  );
}
